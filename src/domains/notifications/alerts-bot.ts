/**
 * The CommerceOS alerts bot: the owner's bot (alerts and the Owner Assistant), never a customer bot (ADR-128).
 *
 * - Two roles, two bots. Customers talk to the shop's own bot (Connectors → Telegram, the customer agent). The owner
 *   talks to the alerts bot: by default the platform bot (TELEGRAM_ALERTS_BOT_TOKEN, nothing to set up), or a second
 *   bot the workspace saves in Settings → Notifications. A bot can't be both: a customer bot is refused as an alerts
 *   bot, and an alerts bot is refused as a customer bot (ChannelService.assertTelegramBotAvailable). There is no
 *   fallback to the customer bot.
 * - Random webhook secrets. A workspace bot gets its own webhook address (`…/webhook/<key>`) and a random secret, both
 *   generated by the server and stored encrypted; the secret can't be worked out from the bot token, and saving the
 *   bot again rotates both. The platform bot uses TELEGRAM_ALERTS_WEBHOOK_SECRET, or else a secret derived from its
 *   token (the platform token is known only to the server).
 * - Workspace bots saved before this change still carry the old token-derived secret until they are registered again
 *   (the next Connect, Send test or save does it); until then the old address accepts them for their own workspace only.
 *
 * Every call goes through the SSRF-guarded client (telegramCall).
 */
import crypto from "crypto";
import { db } from "@/infrastructure/db";
import { decryptCredential, encryptCredential } from "@/lib/security";
import { telegramCall, TELEGRAM_SECRET_HEADER } from "@/domains/social/channels/adapters/telegram.adapter";
import { appBaseUrl } from "@/lib/app-url";
import { AppError } from "@/lib/errors";
import { logger } from "@/lib/logger";
import type { NotificationSettingsRecord } from "@/types/notifications";

/** The platform bot's webhook. A workspace bot's is this plus `/<its key>`. */
export const ALERTS_WEBHOOK_PATH = "/api/v1/notifications/telegram/webhook";
export { TELEGRAM_SECRET_HEADER };

const WEBHOOK_KEY_PATTERN = /^[A-Za-z0-9_-]{32}$/;

export class AlertsBotNotConfiguredError extends AppError {
  constructor(reason: string) {
    super("ALERTS_BOT_NOT_CONFIGURED", `Telegram alerts aren't available on this server yet (${reason}).`, 503);
  }
}

export type AlertsBotSource = "platform" | "workspace";

export interface ResolvedAlertsBot {
  token: string;
  source: AlertsBotSource;
  savedUsername?: string;
}

/**
 * Which alerts bot an update came through. The platform bot serves workspaces without their own bot; a workspace bot
 * serves only that workspace (ADR-127 security review H1).
 */
export type AlertsBotScope = { kind: "platform" } | { kind: "tenant"; tenantId: string };

/** The numeric bot id at the start of a Telegram bot token ("123456789:AA…"), or null for a malformed token. */
export function telegramBotIdOf(token: string): string | null {
  const m = /^(\d{3,20}):[A-Za-z0-9_-]{20,}$/.exec(token.trim());
  return m ? m[1] : null;
}

function platformBotToken(env: NodeJS.ProcessEnv = process.env): string | null {
  const token = env.TELEGRAM_ALERTS_BOT_TOKEN?.trim();
  return token ? token : null;
}

/** The platform bot's id, when one is configured. */
export function platformAlertsBotId(env: NodeJS.ProcessEnv = process.env): string | null {
  const token = platformBotToken(env);
  return token ? telegramBotIdOf(token) : null;
}

/** A workspace's saved alerts bot token (decrypted), or null. */
export function workspaceAlertsBotToken(record: NotificationSettingsRecord | undefined): string | null {
  if (!record?.bot_token_encrypted) return null;
  try {
    const decrypted = decryptCredential<{ bot_token?: string }>(record.bot_token_encrypted);
    const token = typeof decrypted.bot_token === "string" ? decrypted.bot_token.trim() : "";
    return token || null;
  } catch {
    return null; // unreadable secret
  }
}

export function resolveAlertsBot(tenantId?: string, env: NodeJS.ProcessEnv = process.env): ResolvedAlertsBot | null {
  if (tenantId) {
    const settings = db.findNotificationSettings(tenantId);
    const token = workspaceAlertsBotToken(settings);
    if (token) return { token, source: "workspace", savedUsername: settings?.bot_username };
  }
  const platform = platformBotToken(env);
  if (platform) return { token: platform, source: "platform" };
  return null; // never the workspace's customer bot (ADR-128)
}

export function alertsBotConfigured(env: NodeJS.ProcessEnv = process.env, tenantId?: string): boolean {
  return resolveAlertsBot(tenantId, env) !== null;
}

/** The old token-derived secret. Still the platform bot's when TELEGRAM_ALERTS_WEBHOOK_SECRET is unset. */
export function secretForAlertsToken(token: string): string {
  return crypto.createHmac("sha256", token).update("commerceos-alerts-webhook").digest("hex");
}

/** The platform bot's webhook secret: TELEGRAM_ALERTS_WEBHOOK_SECRET (32+ characters), else derived from its token. */
export function platformWebhookSecret(env: NodeJS.ProcessEnv = process.env): string | null {
  const configured = env.TELEGRAM_ALERTS_WEBHOOK_SECRET?.trim();
  if (configured && configured.length >= 32) return configured;
  const token = platformBotToken(env);
  return token ? secretForAlertsToken(token) : null;
}

/** A workspace bot's random webhook secret, when it has one. */
function workspaceWebhookSecret(record: NotificationSettingsRecord | undefined): string | null {
  if (!record?.bot_webhook_secret_encrypted) return null;
  try {
    const decrypted = decryptCredential<{ secret?: string }>(record.bot_webhook_secret_encrypted);
    return typeof decrypted.secret === "string" && decrypted.secret ? decrypted.secret : null;
  } catch {
    return null;
  }
}

/** A fresh webhook address key and random secret for a workspace bot (stored encrypted). */
export function newWorkspaceWebhookIdentity(): Pick<NotificationSettingsRecord, "bot_webhook_key" | "bot_webhook_secret_encrypted"> {
  return {
    bot_webhook_key: crypto.randomBytes(24).toString("base64url"),
    bot_webhook_secret_encrypted: encryptCredential({ secret: crypto.randomBytes(32).toString("base64url") }),
  };
}

/** The webhook path of a workspace bot. */
export function workspaceWebhookPath(key: string): string {
  return `${ALERTS_WEBHOOK_PATH}/${key}`;
}

/**
 * The secret Telegram sends back on every call (X-Telegram-Bot-Api-Secret-Token) for the bot that serves a workspace:
 * its random one, or the platform bot's. Null when no bot is set up.
 */
export function alertsWebhookSecret(env: NodeJS.ProcessEnv = process.env, tenantId?: string): string | null {
  const resolved = resolveAlertsBot(tenantId, env);
  if (!resolved) return null;
  if (resolved.source === "workspace") {
    const record = tenantId ? db.findNotificationSettings(tenantId) : undefined;
    return workspaceWebhookSecret(record) ?? secretForAlertsToken(resolved.token);
  }
  return platformWebhookSecret(env);
}

function matchesSecretConstantTime(expected: string, header: string): boolean {
  const a = crypto.createHash("sha256").update(expected).digest();
  const b = crypto.createHash("sha256").update(header).digest();
  return crypto.timingSafeEqual(a, b);
}

/**
 * A call to the platform bot's address: the platform bot (its secret), or a workspace bot saved before random secrets
 * that hasn't been registered again yet (its token-derived secret, its own workspace only). Null otherwise.
 */
export function identifyAlertsWebhookCall(header: string | null, env: NodeJS.ProcessEnv = process.env): AlertsBotScope | null {
  if (!header) return null;
  const platformExpected = platformWebhookSecret(env);
  if (platformExpected && matchesSecretConstantTime(platformExpected, header)) return { kind: "platform" };
  for (const rec of db.getAllNotificationSettings()) {
    if (!rec.bot_token_encrypted || rec.bot_webhook_key) continue; // registered bots use their own address only
    const token = workspaceAlertsBotToken(rec);
    if (token && matchesSecretConstantTime(secretForAlertsToken(token), header)) return { kind: "tenant", tenantId: rec.tenant_id };
  }
  return null;
}

/** A call to a workspace bot's own address: that workspace, when the random secret matches. Null otherwise. */
export function identifyWorkspaceWebhookCall(key: string, header: string | null): AlertsBotScope | null {
  if (!header || !WEBHOOK_KEY_PATTERN.test(key)) return null;
  const record = db.getAllNotificationSettings().find((r) => r.bot_webhook_key === key && r.bot_token_encrypted);
  const expected = workspaceWebhookSecret(record);
  // Compared even when nothing matched, so a wrong key and a wrong secret take the same time
  const ok = matchesSecretConstantTime(expected ?? crypto.randomBytes(32).toString("hex"), header);
  return ok && record && expected ? { kind: "tenant", tenantId: record.tenant_id } : null;
}

/** Whether a webhook call carries the platform bot's secret (or a not-yet-registered workspace bot's). */
export function isAlertsWebhookCall(header: string | null, env: NodeJS.ProcessEnv = process.env): boolean {
  return identifyAlertsWebhookCall(header, env) !== null;
}

/** Calls the Bot API as the alerts bot (for a workspace when tenantId is given, or the platform bot). */
export async function alertsBotCall(
  method: string,
  params: Record<string, unknown>,
  tenantId?: string
): Promise<Record<string, unknown>> {
  const resolved = resolveAlertsBot(tenantId);
  if (!resolved) throw new AlertsBotNotConfiguredError("TELEGRAM_ALERTS_BOT_TOKEN is not set");
  return telegramCall({ bot_token: resolved.token }, method, params);
}

let usernameCache: { token: string; username: string } | null = null;

/** The bot's @username (for the t.me link), asked from Telegram once per token. Null when it can't be read now. */
export async function alertsBotUsername(tenantId?: string): Promise<string | null> {
  const resolved = resolveAlertsBot(tenantId);
  if (!resolved) return null;
  if (resolved.savedUsername) return resolved.savedUsername;
  if (usernameCache?.token === resolved.token) return usernameCache.username;
  try {
    const me = await alertsBotCall("getMe", {}, tenantId);
    const username = typeof me.username === "string" ? me.username : null;
    if (username) usernameCache = { token: resolved.token, username };
    return username;
  } catch (err) {
    logger.warn("notifications.alerts_bot_getme_failed", { error: err instanceof AppError ? err.code : "error" });
    return null;
  }
}

let webhookRegisteredFor: string | null = null;

/**
 * Points the alerts bot's webhook at this app when APP_URL is https: the platform bot at the shared address, a
 * workspace bot at its own address with its random secret (generated here for a bot saved before random secrets, which
 * also retires its token-derived one). Once per process per bot and secret; Telegram accepts a repeat harmlessly. With
 * an http APP_URL (localhost), linking falls back to polling getUpdates. Call inside a unit: it may save the record.
 */
export async function ensureAlertsWebhook(tenantId?: string): Promise<void> {
  const resolved = resolveAlertsBot(tenantId);
  if (!resolved) throw new AlertsBotNotConfiguredError("TELEGRAM_ALERTS_BOT_TOKEN is not set");
  const base = appBaseUrl();
  if (!base || !base.startsWith("https://")) return;

  let url = `${base}${ALERTS_WEBHOOK_PATH}`;
  let secret = platformWebhookSecret();
  if (resolved.source === "workspace" && tenantId) {
    let record = db.findNotificationSettings(tenantId);
    if (record && (!record.bot_webhook_key || !workspaceWebhookSecret(record))) {
      record = db.saveNotificationSettings({ ...record, ...newWorkspaceWebhookIdentity(), updated_at: new Date().toISOString() });
    }
    secret = workspaceWebhookSecret(record);
    if (!record?.bot_webhook_key || !secret) throw new AppError("ALERTS_BOT_WEBHOOK", "The alerts bot's webhook could not be prepared.", 500);
    url = `${base}${workspaceWebhookPath(record.bot_webhook_key)}`;
  }
  if (!secret) throw new AlertsBotNotConfiguredError("no webhook secret");
  const cacheKey = crypto.createHash("sha256").update(`${resolved.token}|${url}|${secret}`).digest("hex");
  if (webhookRegisteredFor === cacheKey) return;
  await alertsBotCall("setWebhook", { url, secret_token: secret, allowed_updates: ["message"] }, tenantId);
  webhookRegisteredFor = cacheKey;
}

/** Tests: forget the cached username and webhook registration. */
export function resetAlertsBotForTesting(): void {
  usernameCache = null;
  webhookRegisteredFor = null;
}
