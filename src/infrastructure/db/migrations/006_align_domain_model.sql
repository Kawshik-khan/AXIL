-- ============================================================
-- CommerceOS Migration 006: the application store in Postgres (FIX_IMPLEMENTATION_PLAN FX-41, ADR-108)
--
-- Everything lives in its own schema, `commerceos`, so it never collides with the legacy tables that migrations
-- 001-005 created in `public` from a schema that had drifted from the domain types (those files are kept in
-- migrations/legacy/ and no longer run).
--
-- Every row keeps the full domain record in `data` (jsonb), exactly as the TypeScript types define it. The columns used
-- for constraints and indexes are GENERATED from `data`, so they can never disagree with the record. The writer only
-- sets id, tenant_id, created_at and data.
--
-- Core aggregates (identity, catalog and inventory, customers, orders, social inbox, automation runs) get their own
-- tables with constraints; the remaining collections are JSONB documents in `commerceos.documents` (FX-44).
--
-- Constraints that span rows are DEFERRABLE INITIALLY DEFERRED: the store writes a batch of changes in one
-- transaction, and a child row may be written before its parent within that batch. They are checked at COMMIT.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS commerceos;

-- ── Single writer (replaces the .data/commerceos.lock file of FX-24) ─────────────────────────────────────────────
-- One row. The owning process renews heartbeat_at; another process may take over only after the lease has expired.
-- Every write transaction locks this row and checks the owner first (fencing).
CREATE TABLE IF NOT EXISTS commerceos.store_writer (
    id            integer     PRIMARY KEY CHECK (id = 1),
    owner         text        NOT NULL,
    host          text        NOT NULL,
    pid           integer     NOT NULL,
    started_at    timestamptz NOT NULL DEFAULT now(),
    heartbeat_at  timestamptz NOT NULL DEFAULT now()
);

