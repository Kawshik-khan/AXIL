    created_at      timestamptz,
    row_updated_at  timestamptz NOT NULL DEFAULT now(),
    data            jsonb       NOT NULL,
    status          text GENERATED ALWAYS AS (data->>'status') STORED
);

CREATE TABLE IF NOT EXISTS commerceos.automation_executions (
    id              text        PRIMARY KEY,
    tenant_id       text        NOT NULL,
    seq             bigint      GENERATED BY DEFAULT AS IDENTITY,
    created_at      timestamptz,
    row_updated_at  timestamptz NOT NULL DEFAULT now(),
    data            jsonb       NOT NULL,
    automation_id   text GENERATED ALWAYS AS (data->>'automation_id') STORED,
    status          text GENERATED ALWAYS AS (data->>'status') STORED
);
CREATE INDEX IF NOT EXISTS automation_executions_tenant_created_idx ON commerceos.automation_executions (tenant_id, created_at DESC);

-- ── Every other collection: JSONB documents (FX-44) ──────────────────────────────────────────────────────────────
-- Growth, intelligence, operations, enterprise, autonomous, AI and platform-configuration collections are low-write
-- and document-shaped. tenant_id is NULL for platform-scope documents.
CREATE TABLE IF NOT EXISTS commerceos.documents (
    collection      text        NOT NULL,
    id              text        NOT NULL,
    tenant_id       text,
    seq             bigint      GENERATED BY DEFAULT AS IDENTITY,
    created_at      timestamptz,
    row_updated_at  timestamptz NOT NULL DEFAULT now(),
    data            jsonb       NOT NULL,
    PRIMARY KEY (collection, id)
);
CREATE INDEX IF NOT EXISTS documents_tenant_idx ON commerceos.documents (tenant_id, collection, row_updated_at DESC);
CREATE INDEX IF NOT EXISTS documents_collection_seq_idx ON commerceos.documents (collection, seq);

-- Records Postgres refused (a constraint, a malformed value), kept here in the same transaction so they survive a
-- restart and stay reported until they are saved or an operator resolves them. `data` is NULL for a refused delete.
CREATE TABLE IF NOT EXISTS commerceos.refused_rows (
    collection      text        NOT NULL,
    id              text        NOT NULL,
    tenant_id       text,
    op              text        NOT NULL CHECK (op IN ('upsert', 'delete')),
    reason          text        NOT NULL,
    constraint_name text,
    data            jsonb,
    refused_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (collection, id)
);

-- Store-level values that are not collections of records.
CREATE TABLE IF NOT EXISTS commerceos.store_meta (
    key             text        PRIMARY KEY,
    value           jsonb       NOT NULL,
    row_updated_at  timestamptz NOT NULL DEFAULT now()
);
